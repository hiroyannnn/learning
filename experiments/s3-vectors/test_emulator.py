import os
import unittest
from configparser import ConfigParser
from pathlib import Path

import boto3
from botocore.config import Config

from experiment import DIMENSION, REGION, call_query, prepare_batch, query_options, temporary_index
from fixtures import Document, Query

EMULATOR_ACCOUNT = "000000000000"


def emulator_client(state_dir, port):
    credentials = ConfigParser(interpolation=None)
    with (state_dir / "emulator_credentials").open(encoding="utf-8") as stream:
        credentials.read_file(stream)
    key = credentials["default"]["aws_access_key_id"]
    if not key.startswith("EMULATOR"):
        raise ValueError("Expected credentials generated by AWS Emulator")

    session = boto3.Session(
        aws_access_key_id=key,
        aws_secret_access_key=credentials["default"]["aws_secret_access_key"],
        region_name=REGION,
    )
    local_options = {
        "endpoint_url": f"https://127.0.0.1:{port}",
        "verify": str(state_dir / "ca.pem"),
        "config": Config(
            defaults_mode="legacy",
            ignore_configured_endpoint_urls=True,
            inject_host_prefix=False,
            proxies={},
            retries={"total_max_attempts": 1},
            connect_timeout=3,
            read_timeout=5,
        ),
    }
    account = session.client("sts", **local_options).get_caller_identity()["Account"]
    if account != EMULATOR_ACCOUNT:
        raise ValueError("Expected the AWS Emulator account 000000000000")
    return session.client("s3vectors", **local_options)


@unittest.skipUnless(os.getenv("S3V_EMULATOR_DIR"), "run with an AWS Emulator state directory")
class EmulatorTests(unittest.TestCase):
    def test_vector_rank_filter_and_resource_lifecycle(self):
        state_dir = Path(os.environ["S3V_EMULATOR_DIR"])
        port = int(os.environ.get("S3V_EMULATOR_PORT", "9297"))
        client = emulator_client(state_dir, port)
        corpus = [
            Document("matching", "coffee", "豆挽きの最中に異音がする"),
            Document("distractor", "air", "空気清浄機の電源が入らない"),
        ]
        matching = [1.0, 0.0] + [0.0] * (DIMENSION - 2)
        orthogonal = [0.0, 1.0] + [0.0] * (DIMENSION - 2)
        batch, _ = prepare_batch(corpus, [matching, orthogonal])
        query = Query("言い換え", "ミルがうるさい", ("matching",))

        with temporary_index(client, EMULATOR_ACCOUNT) as index_arn:
            client.put_vectors(indexArn=index_arn, vectors=batch)

            hits, _ = call_query(client, query_options(index_arn, "ベクトル", query, matching))
            self.assertEqual([hit["key"] for hit in hits], ["matching", "distractor"])
            self.assertAlmostEqual(hits[0]["distance"], 0.0)
            self.assertAlmostEqual(hits[1]["distance"], 1.0)

            filtered = query_options(index_arn, "ベクトル", query, matching, category="air")
            hits, _ = call_query(client, filtered)
            self.assertEqual([hit["key"] for hit in hits], ["distractor"])


if __name__ == "__main__":
    unittest.main()
